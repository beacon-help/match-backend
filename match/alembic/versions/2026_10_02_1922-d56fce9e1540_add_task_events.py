CREATE_TASKS_WITH_STATUS_VIEW = """
CREATE VIEW tasks_with_status AS
SELECT
    tasks.*,
    CASE (
        SELECT task_events.type
        FROM task_events
        WHERE task_events.task_id = tasks.id
        ORDER BY task_events.occurred_at DESC, task_events.id DESC
        LIMIT 1
    )
        WHEN 'offered' THEN 'pending'
        WHEN 'approved' THEN 'approved'
        WHEN 'closed' THEN 'cancelled'
        WHEN 'succeeded' THEN 'succeeded'
        WHEN 'failed' THEN 'failed'
        ELSE 'open'
    END AS status
FROM tasks
"""

