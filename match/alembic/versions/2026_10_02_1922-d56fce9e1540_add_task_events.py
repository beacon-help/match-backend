def _event(
    task_id: int,
    type: str,
    actor_id: int,
    occurred_at: datetime,
    helper_id: int | None = None,
    message: str | None = None,
) -> dict:
    return {
        "task_id": task_id,
        "type": type,
        "actor_id": actor_id,
        "helper_id": helper_id,
        "message": message,
        "occurred_at": occurred_at,
    }


def _task_events(task: sa.Row) -> list[dict]:
    events = [_event(task.id, "created", task.owner_id, task.created_at)]
    for offer in json.loads(task.helper_offers or "[]"):
        offered_at = datetime.fromisoformat(offer["offered_at"])
        if offered_at.tzinfo is not None:
            offered_at = offered_at.astimezone(timezone.utc).replace(tzinfo=None)
        events.append(
            _event(
                task.id,
                "offered",
                offer["user_id"],
                offered_at,
                helper_id=offer["user_id"],
                message=offer["message"],
            )
        )

    if STATUS_BY_EVENT_TYPE[events[-1]["type"]] != task.status:
        # History before task_events is unknown; one closing event makes status derivable.
        event_type = LAST_EVENT_TYPE_BY_STATUS[task.status]
        helper_id = task.helper_id if task.helper_id is not None else events[-1]["helper_id"]
        actor_id = helper_id if event_type == "offered" else task.owner_id
        occurred_at = max(
            [event["occurred_at"] for event in events]
            + ([task.updated_at] if task.updated_at else [])
        )
        events.append(_event(task.id, event_type, actor_id, occurred_at, helper_id=helper_id))
    return events


