def _restore_statuses() -> None:
    connection = op.get_bind()
    events = connection.execute(
        sa.select(task_events_table.c.task_id, task_events_table.c.type).order_by(
            task_events_table.c.occurred_at, task_events_table.c.id
        )
    )
    last_event_type = {event.task_id: event.type for event in events}
    for task_id in connection.execute(sa.select(tasks_table.c.id)).scalars():
        status = STATUS_BY_EVENT_TYPE[last_event_type.get(task_id, "created")]
        connection.execute(
            tasks_table.update().where(tasks_table.c.id == task_id).values(status=status)
        )


